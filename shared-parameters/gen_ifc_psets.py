"""Write the Revit IFC exporter's user-defined property set file from the OpenBEP manifest.

Every OpenBEP shared parameter, and every built-in Revit parameter the manifest names plainly, goes in a property set named OpenBEP, under its Revit name (what the BEP Builder's IDS checks).
Where the manifest's "IFC target" names a standard IFC4 property (Pset_*.Name) that buildingSMART's templates define,
the parameter is also written there, on the IFC classes the template applies to.

Needs ifcopenshell (pip install ifcopenshell) for the IFC4 property set templates.
Usage: python gen_ifc_psets.py   ->  OpenBEP_IFC_PropertySets_v0.1.txt
"""
import csv, re, collections, os
import ifcopenshell, ifcopenshell.util.pset

VER = '0.1'
HERE = os.path.dirname(os.path.abspath(__file__))
SCHEMA = ifcopenshell.schema_by_name('IFC4') if hasattr(ifcopenshell, 'schema_by_name') else ifcopenshell.ifcopenshell_wrapper.schema_by_name('IFC4')
TPL = ifcopenshell.util.pset.get_template('IFC4')

# Revit IFC exporter data types, from the Revit parameter's data type
REVIT = {'TEXT': 'Label', 'MULTILINETEXT': 'Text', 'YESNO': 'Boolean', 'INTEGER': 'Integer', 'NUMBER': 'Real',
         'LENGTH': 'Length', 'AREA': 'Area', 'VOLUME': 'Volume'}

# Corrections to manifest rows, kept here because the manifest is generated.
# The Revit name the exporter reads, where the manifest's name carries a note.
REVIT_NAME = {'Visual Light Transmittance - analytical properties': 'Visual Light Transmittance',
              # The "Voltage" type parameter that panel, device and light families tie to their electrical connector.
              # The panel's own Distribution System is an element id, not a number the exporter can write.
              'Voltage / Distribution System': 'Voltage', 'Voltage (connector)': 'Voltage'}
# Built-in parameters with a Revit unit: the exporter writes a measure and converts from Revit's internal units.
# Shared NUMBER parameters stay Real: they hold the plain number, and the exporter would rescale it.
REVIT_UNIT = {'V': 'ElectricVoltage', 'A': 'ElectricCurrent'}
# IFC targets missing from a manifest row, keyed (Revit name, element type).
IFC_TARGET = {('Flow', 'Fans'): 'Pset_FanTypeCommon.NominalAirFlowRate'}


def entity_ok(name):
    try: SCHEMA.declaration_by_name(name); return True
    except Exception: return False


def standard(target):
    """[(pset, prop, template prop, applicable classes)] for each IFC4 standard property in an "IFC target" cell."""
    out = []
    for alt in (target or '').split(' / '):
        m = re.fullmatch(r'(Pset_\w+)\.(\w+)', alt.strip())
        if not m: continue
        pt = TPL.get_by_name(m[1])
        if not pt: continue
        prop = next((p for p in pt.HasPropertyTemplates if p.Name == m[2]), None)
        if not prop: continue
        ents = [e.split('/')[0].strip() for e in re.split(r'[,|]', pt.ApplicableEntity or '') if e.strip()]
        out.append((m[1], m[2], prop, ents))
    return out


def classes(ents, scope):
    """Occurrence classes for instance parameters, type classes for type parameters."""
    res = []
    for e in ents:
        base = e[:-4] if e.endswith('Type') and entity_ok(e[:-4]) else e
        c = base + 'Type' if scope == 'type' and not base.endswith('Type') else base
        if scope == 'type' and not entity_ok(c): continue
        if c not in res: res.append(c)
    return res


def main():
    # Shared parameters, plus built-in Revit parameters whose manifest name is a plain Revit name (Type Name, Mark, Width...);
    # rows like "Size / Diameter" or "Room / Space (calculated, read-only)" describe several parameters and are left out.
    rows = []
    for r in csv.DictReader(open(os.path.join(HERE, f'OpenBEP_Parameters_Manifest_v{VER}.csv'), encoding='utf-8-sig')):
        r['Parameter (Revit name)'] = REVIT_NAME.get(r['Parameter (Revit name)'], r['Parameter (Revit name)'])
        r['IFC target'] = r['IFC target'] or IFC_TARGET.get((r['Parameter (Revit name)'], r['Element type']), '')
        if r['Shared or built-in'] == 'Shared' or re.fullmatch(r'[\w #]+', r['Parameter (Revit name)']): rows.append(r)
    own = {'instance': {}, 'type': {}}
    std = collections.OrderedDict()   # (pset, I/T, classes) -> {prop: (type, revit name)}
    mapped = set()
    for r in rows:
        n, sc, dt = r['Parameter (Revit name)'], r['Instance or type'].strip().lower(), REVIT.get(r['Data type'], 'Label')
        if r['Shared or built-in'] != 'Shared' and dt == 'Real': dt = REVIT_UNIT.get(r['Unit'], dt)
        sc = 'type' if sc == 'type' else 'instance'
        own[sc][n] = dt
        for ps, prop, _, ents in standard(r['IFC target']):
            cl = classes(ents, sc)
            if not cl: continue
            std.setdefault((ps, 'T' if sc == 'type' else 'I', ','.join(cl)), {})[prop] = (dt, n)
            mapped.add(n)
    L = ['#', f'# OpenBEP user-defined property sets for the Revit IFC exporter, v{VER}. Generated by gen_ifc_psets.py from the manifest.',
         '# Use: IFC export > Modify setup > Property Sets > Export user defined property sets, and pick this file.',
         '# Also turn on "Export IFC common property sets" and "Export base quantities".',
         '# Property set OpenBEP, on occurrences: every OpenBEP shared parameter and plainly named built-in parameter under its Revit name',
         '# (what the BEP Builder\'s IDS checks), type parameters included.',
         '# Pset_* blocks: the same parameters again under the standard IFC4 property their "IFC target" names.', '#']
    # One OpenBEP set, on occurrences, with the type parameters in it too (the exporter reads a type parameter through the instance).
    # A second OpenBEP set on types gets copied onto door and window occurrences, and an IDS checker then reads only one of the two.
    L.append('PropertySet:\tOpenBEP\tI\tIfcElement,IfcSpatialElement,IfcZone')
    L += [f'\t{n}\t{t}' for n, t in sorted({**own['type'], **own['instance']}.items())]
    for (ps, it, cl), props in std.items():
        L.append(f'PropertySet:\t{ps}\t{it}\t{cl}')
        L += [f'\t{p}\t{t}\t{n}' for p, (t, n) in sorted(props.items())]
    dst = os.path.join(HERE, f'OpenBEP_IFC_PropertySets_v{VER}.txt')
    open(dst, 'w', encoding='utf-8', newline='\r\n').write('\n'.join(L) + '\n')
    print(f'{len(own["instance"])} instance and {len(own["type"])} type parameters in OpenBEP; {len(mapped)} also in {len({k[0] for k in std})} standard IFC4 property sets -> {dst}')


if __name__ == '__main__':
    main()
